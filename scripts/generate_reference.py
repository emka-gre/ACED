"""Record what the research pipeline produces, stage by stage, as the parity reference.

Task 2.1a. The thesis archive contains no saved pipeline output, so the numbers the port is
required to reproduce have to be generated by running the research code once. This script
imports the research modules straight from the archive — it deliberately does not go through
`aced`, or it would be checking the port against itself.

Stages, in dependency order:

    pose        video -> per-frame MediaPipe landmarks (needs mediapipe; Python 3.11 only)
    features    landmark CSV -> the 8 selected features per frame, then 60-frame windows at
                stride 20, flattened to 480 columns
    predict     windows -> per-window class and, for the LSTM, probability
                (the LSTM half needs keras; the SVM half needs only scikit-learn)

Each stage writes its output to fixtures/reference/ alongside a meta file recording the
interpreter and library versions that produced it, because a reference generated under a
different numpy is a reference with an asterisk on it.

Run everything under the pinned environment:

    python scripts/generate_reference.py --stage all --video ~/Desktop/aced-thesis-archive/\\
        extracted/bachelor-project-main/video_62_B_Ema.MOV
"""

from __future__ import annotations

import argparse
import json
import platform
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
REFERENCE_DIR = ROOT / "fixtures" / "reference"
DEFAULT_LANDMARKS = ROOT / "fixtures" / "landmarks" / "reference_62_B.csv"
DEFAULT_ARCHIVE = (
    Path.home() / "Desktop" / "aced-thesis-archive" / "extracted" / "bachelor-project-main"
)

WINDOW = 60
STRIDE = 20


def load_research_modules(archive: Path) -> Any:
    """Put the archive on the path and import the research code from it.

    The research modules import each other by top-level name (`from features.features import
    Feature`), so the archive root has to be on `sys.path`, and `streamlit/` too for the
    pipeline modules that sit there.
    """
    if not archive.exists():
        raise SystemExit(f"Archive not found at {archive}. See THESIS_ARCHIVE.md.")
    for path in (archive, archive / "streamlit"):
        if str(path) not in sys.path:
            sys.path.insert(0, str(path))


def environment() -> dict[str, str]:
    versions = {"python": platform.python_version(), "platform": platform.platform()}
    for name in ("numpy", "pandas", "sklearn", "keras", "mediapipe", "cv2"):
        try:
            module = __import__(name)
        except ImportError:
            continue
        versions[name] = str(getattr(module, "__version__", "unknown"))
    return versions


def write_meta(stage: str, outputs: list[Path], extra: dict[str, Any] | None = None) -> None:
    meta_path = REFERENCE_DIR / f"{stage}_meta.json"
    meta: dict[str, Any] = {
        "stage": stage,
        "generated_by": "scripts/generate_reference.py",
        "source": "research pipeline in the thesis archive, imported unmodified",
        "environment": environment(),
        "outputs": [str(path.relative_to(ROOT)) for path in outputs],
    }
    if extra:
        meta.update(extra)
    meta_path.write_text(json.dumps(meta, indent=2) + "\n")
    print(f"  meta -> {meta_path.relative_to(ROOT)}")


def stage_pose(archive: Path, video: Path) -> None:
    """Run the research pose extractor over the reference video."""
    from pose_extraction import PoseExtraction  # type: ignore[import-not-found]

    print(f"pose: {video.name}")
    frames = PoseExtraction(video_path=str(video)).extract_poses()
    if frames.empty:
        raise SystemExit(
            "pose extraction produced nothing — check the video path and codec support"
        )

    out = REFERENCE_DIR / "pose_reference.csv"
    frames.to_csv(out, index=False)
    detected = len(frames)
    span = int(frames["frame"].max()) + 1
    print(f"  {detected} detected frames over {span} source frames -> {out.relative_to(ROOT)}")
    write_meta(
        "pose",
        [out],
        {
            "video": video.name,
            "detected_frames": detected,
            "source_frames": span,
            "note": "frames without a detected pose are dropped; frame indices carry the gaps",
        },
    )


def stage_features(archive: Path, landmarks: Path) -> None:
    """Run the research feature + windowing code over a landmark CSV."""
    import pandas as pd
    from dataset_generation import Dataset_generation  # type: ignore[import-not-found]

    print(f"features: {landmarks.name}")
    poses = pd.read_csv(landmarks)
    generator = Dataset_generation(poses)

    per_frame = generator.dataset_features()
    segments, windows = generator.dataset_segmentation()

    features_out = REFERENCE_DIR / "features_reference.csv"
    segments_out = REFERENCE_DIR / "segments_reference.csv"
    per_frame.to_csv(features_out, index=False)
    segments.to_csv(segments_out, index=False)

    print(
        f"  {len(per_frame)} frames x {per_frame.shape[1]} cols -> {features_out.relative_to(ROOT)}"
    )
    print(
        f"  {len(segments)} windows x {segments.shape[1]} cols -> {segments_out.relative_to(ROOT)}"
    )
    write_meta(
        "features",
        [features_out, segments_out],
        {
            "landmarks": landmarks.name,
            "frames": len(per_frame),
            "windows": len(segments),
            "window_shape": list(windows.shape),
            "window_length": WINDOW,
            "stride": STRIDE,
        },
    )


def stage_predict(archive: Path) -> None:
    """Classify the recorded windows with each shipped model."""
    import numpy as np
    import pandas as pd

    segments_path = REFERENCE_DIR / "segments_reference.csv"
    if not segments_path.exists():
        raise SystemExit("run the features stage first — no segments_reference.csv")

    segments = pd.read_csv(segments_path)
    segments = segments.loc[:, ~segments.columns.str.startswith("Unnamed")]
    outputs: list[Path] = []
    recorded: dict[str, Any] = {}

    # --- LSTM: externally scaled, sigmoid output, threshold 0.5 -----------------------
    try:
        import joblib
        import keras
    except ImportError as exc:
        print(f"  skip LSTM: {exc.name} not installed (needs the pinned Python 3.11 environment)")
    else:
        scaler = joblib.load(archive / "training" / "LTSM" / "scaler.pkl")
        model = keras.models.load_model(
            archive / "training" / "MODELS" / "LSTM_model.keras", compile=False
        )

        # The research code aligns to the scaler's own column order before transforming.
        aligned = segments.reindex(columns=list(scaler.feature_names_in_))
        if aligned.isna().to_numpy().any():
            raise SystemExit(
                "segment columns do not cover the scaler's features — schema divergence"
            )

        scaled = scaler.transform(aligned)
        sequence = np.asarray(scaled, dtype=np.float32).reshape(
            (-1, WINDOW, scaled.shape[1] // WINDOW)
        )
        probabilities = np.asarray(model.predict(sequence, verbose=0)).reshape(-1)
        predictions = (probabilities >= 0.5).astype(int)

        out = REFERENCE_DIR / "predictions_lstm_reference.csv"
        pd.DataFrame(
            {
                "window": range(len(predictions)),
                "probability": probabilities,
                "prediction": predictions,
            }
        ).to_csv(out, index=False)
        outputs.append(out)
        recorded["lstm"] = {
            "windows": len(predictions),
            "sound": int(predictions.sum()),
            "threshold": 0.5,
            "scaling": "external, from training/LTSM/scaler.pkl",
        }
        print(
            f"  LSTM: {int(predictions.sum())}/{len(predictions)} windows sound "
            f"-> {out.relative_to(ROOT)}"
        )

    # --- SVM: scales internally, no calibrated probability ----------------------------
    import joblib

    svm = joblib.load(archive / "training" / "MODELS" / "SVM_model")
    aligned_svm = segments.reindex(columns=list(svm.feature_names_in_))
    if aligned_svm.isna().to_numpy().any():
        raise SystemExit("segment columns do not cover the SVM's features — schema divergence")

    svm_predictions = svm.predict(aligned_svm).astype(int)
    margins = svm.decision_function(aligned_svm)

    out = REFERENCE_DIR / "predictions_svm_reference.csv"
    pd.DataFrame(
        {"window": range(len(svm_predictions)), "margin": margins, "prediction": svm_predictions}
    ).to_csv(out, index=False)
    outputs.append(out)
    recorded["svm"] = {
        "windows": len(svm_predictions),
        "sound": int(svm_predictions.sum()),
        "scaling": "internal to the saved Pipeline; raw features passed in",
        "confidence": "decision-function margin only; probability=False",
    }
    print(
        f"  SVM: {int(svm_predictions.sum())}/{len(svm_predictions)} windows sound "
        f"-> {out.relative_to(ROOT)}"
    )

    write_meta("predictions", outputs, {"models": recorded})


def main() -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument(
        "--archive", type=Path, default=DEFAULT_ARCHIVE, help="extracted thesis archive root"
    )
    parser.add_argument(
        "--landmarks",
        type=Path,
        default=DEFAULT_LANDMARKS,
        help="landmark CSV for the features stage",
    )
    parser.add_argument("--video", type=Path, help="reference video, required for the pose stage")
    parser.add_argument(
        "--stage",
        choices=["all", "pose", "features", "predict"],
        default="all",
        help="which stage to record; 'all' skips pose unless --video is given",
    )
    args = parser.parse_args()

    REFERENCE_DIR.mkdir(parents=True, exist_ok=True)
    load_research_modules(args.archive)

    if args.stage in ("all", "pose"):
        if args.video:
            stage_pose(args.archive, args.video)
        elif args.stage == "pose":
            raise SystemExit("--video is required for the pose stage")
        else:
            print("pose: skipped (no --video given)")

    if args.stage in ("all", "features"):
        stage_features(args.archive, args.landmarks)

    if args.stage in ("all", "predict"):
        stage_predict(args.archive)

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
